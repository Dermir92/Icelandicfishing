export const spots = fishingSpotsSeed;

export function getSpotBySlug(slug: string) {
  return spots.find((spot) => spot.slug === slug);
}

export function getNearbySpots(spot: FishingSpot, limit = 3) {
  return spots
    .filter((candidate) => candidate.id !== spot.id)
    .sort((left, right) => {
      const leftScore = Number(left.region === spot.region) + Number(left.waterType === spot.waterType);
      const rightScore =
        Number(right.region === spot.region) + Number(right.waterType === spot.waterType);
      return rightScore - leftScore;
    })
    .slice(0, limit);
}
